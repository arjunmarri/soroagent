// Prompt templates and response parsers.
//
// Every action has a { system, user } template. Templates use {{placeholders}}; site profiles
// (extension/sites/*.js) can override any action's system or user template for their site.
// Placeholders available to every template:
//   {{persona}}      the assistant persona below
//   {{title}}        page title            {{url}}       page URL
//   {{content}}      the text being worked on (page text, posts, selection…)
//   {{page}}         title + URL + content wrapped in <page> tags, with a truncation note
//   {{count}}        number of items (posts, blocks) in {{content}}, when the site provides items
//   {{context}}      extra context from the site profile (e.g. "Search results for …")
//   {{note}}         truncation note ("" when nothing was cut)
//   {{question}}     the user's question (ask action only)
// Pure functions: unit tested without a browser.
(function (root) {
  'use strict';

  const SoroAgent = (root.SoroAgent = root.SoroAgent || {});

  const PERSONA =
    "You are SoroAgent, an assistant running inside the user's browser. " +
    'Be accurate, concise and concrete. Use Markdown. Never invent facts that are not in the provided content.';

  const DEFAULT_PROMPTS = Object.freeze({
    summarize: {
      system: '{{persona}}',
      user:
        '{{page}}\n\nSummarize this web page.\n' +
        'Format:\n**TL;DR:** one sentence.\n\n**Key points**\n- 3 to 7 bullets with the concrete facts, numbers and claims.\n\n' +
        'If something is notably missing, one-sided or promotional, add a short **Worth noting** line.',
    },
    // Long content is summarized in parts: notes per part, then {{content}} = all notes for summarize.
    notes: {
      system: '{{persona}}',
      user:
        '{{context}}\n\n<content>\n{{content}}\n</content>\n\n' +
        'Write compact notes (max 12 bullets) on the key points, notable items (keep names and @handles), numbers and ' +
        'sentiment. These notes will be merged with notes on the other parts into one summary.',
    },
    ask: {
      system:
        '{{persona}}\nAnswer questions about the page below. If the page does not contain the answer, say so ' +
        'and answer from general knowledge only if the user asks you to.\n\n{{page}}',
      user: '{{question}}',
    },
    save: {
      system: 'You label saved web snippets. Reply with JSON only, no prose.',
      user:
        'Page title: {{title}}\nURL: {{url}}\n\n<snippet>\n{{content}}\n</snippet>\n\n' +
        'Return JSON: {"title": "a specific title, max 80 chars", "summary": "1-2 sentences with the key information", ' +
        '"tags": ["1 to 4 short lowercase topic tags"]}',
    },
    // Whole-page check: was the main content written by a person or generated by AI?
    aiCheck: {
      system:
        'You are an expert at telling human-written text from AI-generated text. Judge style, not topic. ' +
        'Signals of AI generation: uniform sentence rhythm, generic hedging ("it\'s important to note"), stock phrases ' +
        '("delve", "in today\'s fast-paced world", "game-changer", "unlock"), list-heavy structure with balanced ' +
        'pros/cons, no first-hand detail, conclusions that restate the intro. Signals of human writing: specific personal ' +
        'experience, uneven rhythm, idiosyncratic opinions, typos and slang, concrete details only an insider would know. ' +
        'Reply with JSON only.',
      user:
        '{{page}}\n\nEstimate how likely it is that the main content above was generated by AI rather than written by a person.\n' +
        'Return JSON: {"ai_probability": 0-100, "confidence": "low" | "medium" | "high", ' +
        '"signals": ["2 to 5 short, specific observations quoting or pointing at the text"]}',
    },
    // Per-item check for sites that provide items (posts, comments), numbered [1], [2]…
    aiCheckItems: {
      system:
        'You are an expert at telling human-written posts from AI-generated ones. Judge style, not topic or opinion. ' +
        'AI signals: generic hype or motivational tone, stock phrases, emoji-bullet structure, engagement bait, no ' +
        'specifics. Human signals: specific details, personal voice, slang, typos, replies that engage with someone. ' +
        'Short posts are hard to judge: keep their scores near 50 unless the signals are clear. Reply with JSON only.',
      user:
        '{{content}}\n\nFor each numbered item, estimate the probability (0-100) that it was generated by AI.\n' +
        'Return JSON: {"scores": {"<number>": {"ai": 0-100, "why": "max 8 words"}}}',
    },
  });

  function render(template, vars) {
    return String(template || '').replace(/\{\{(\w+)\}\}/g, (_, name) => (vars[name] === undefined ? '' : String(vars[name])));
  }

  /** Placeholder values for a page { title, url, text, truncated }, plus any extras. */
  function pageVars(page, extra = {}) {
    const note = page.truncated ? '[Content was truncated to fit the model context.]' : '';
    const content = page.text || '';
    return {
      persona: PERSONA,
      title: page.title || '(untitled)',
      url: page.url || '',
      content,
      note,
      page: `Title: ${page.title || '(untitled)'}\nURL: ${page.url || ''}\n\n<page>\n${content}\n</page>${note ? `\n${note}` : ''}`,
      count: '',
      context: '',
      question: '',
      ...extra,
    };
  }

  /** Builds chat messages for an action; `sitePrompts` overrides the default templates per action. */
  function buildMessages(action, vars, sitePrompts) {
    const base = DEFAULT_PROMPTS[action];
    if (!base) throw new Error(`Unknown prompt action: ${action}`);
    const template = { ...base, ...((sitePrompts && sitePrompts[action]) || {}) };
    const messages = [];
    const system = render(template.system, vars).trim();
    if (system) messages.push({ role: 'system', content: system });
    if (template.user) messages.push({ role: 'user', content: render(template.user, vars).trim() });
    return messages;
  }

  // Pulls the first JSON object out of a model reply, tolerating code fences and chatter.
  function parseJsonLoose(text) {
    const cleaned = SoroAgent.stripThinking(text || '')
      .replace(/```(?:json)?/gi, '')
      .trim();
    try {
      return JSON.parse(cleaned);
    } catch {
      // fall through to scanning for a balanced object
    }
    const start = cleaned.indexOf('{');
    if (start < 0) return null;
    let depth = 0;
    let inString = false;
    for (let i = start; i < cleaned.length; i++) {
      const ch = cleaned[i];
      if (inString) {
        if (ch === '\\') i++;
        else if (ch === '"') inString = false;
      } else if (ch === '"') inString = true;
      else if (ch === '{') depth++;
      else if (ch === '}' && --depth === 0) {
        try {
          return JSON.parse(cleaned.slice(start, i + 1));
        } catch {
          return null;
        }
      }
    }
    return null;
  }

  // Accepts 0-100 or a 0-1 fraction (e.g. 0.72) and returns an integer percentage.
  function toPercent(value) {
    const n = Number(String(value).replace('%', '').trim());
    if (value === null || value === '' || !Number.isFinite(n)) return null;
    const pct = n > 0 && n < 1 ? n * 100 : n;
    return Math.max(0, Math.min(100, Math.round(pct)));
  }

  function verdictFor(percent) {
    if (percent >= 70) return 'ai';
    if (percent <= 30) return 'human';
    return 'mixed';
  }

  /** Whole-page AI check → { aiPercent, verdict, confidence, signals }, or null if unusable. */
  function parseAiCheck(text) {
    const json = parseJsonLoose(text);
    if (!json) return null;
    const aiPercent = toPercent(json.ai_probability ?? json.aiProbability ?? json.ai ?? json.probability);
    if (aiPercent === null) return null;
    const conf = String(json.confidence || '').toLowerCase();
    const signals = (Array.isArray(json.signals) ? json.signals : [])
      .map((s) => String(s).replace(/\s+/g, ' ').trim().slice(0, 200))
      .filter(Boolean)
      .slice(0, 5);
    return {
      aiPercent,
      verdict: verdictFor(aiPercent),
      confidence: ['low', 'medium', 'high'].includes(conf) ? conf : 'low',
      signals,
    };
  }

  /**
   * Per-item AI check → Map(id → { ai, why }) for the given valid ids. Accepts the documented
   * {"scores": {"1": {...}}} and the variations small models produce: keys like "[1]", "#1" or
   * "1.", plain numbers instead of objects, and lists of { id, ai }.
   */
  function parseAiScores(text, validIds) {
    const json = parseJsonLoose(text) || {};
    let scores = json.scores !== undefined ? json.scores : json;
    if (Array.isArray(scores)) {
      scores = Object.fromEntries(scores.filter((e) => e && typeof e === 'object').map((e, i) => [e.id ?? e.item ?? i + 1, e]));
    }
    const byId = new Map();
    for (const [key, entry] of Object.entries(scores && typeof scores === 'object' ? scores : {})) {
      const id = Number(String(key).replace(/[^\d]/g, ''));
      if (Number.isInteger(id) && !byId.has(id)) byId.set(id, entry);
    }
    const out = new Map();
    for (const id of validIds) {
      const entry = byId.get(id);
      if (entry === undefined || entry === null) continue;
      const isObj = typeof entry === 'object';
      const ai = toPercent(isObj ? entry.ai ?? entry.score ?? entry.probability : entry);
      if (ai === null) continue;
      out.set(id, { ai, why: isObj ? String(entry.why || entry.reason || '').trim().slice(0, 80) : '' });
    }
    return out;
  }

  function parseSnippetMeta(text, fallbackTitle) {
    const json = parseJsonLoose(text) || {};
    const clean = (value, max) => String(value || '').replace(/\s+/g, ' ').trim().slice(0, max);
    const tags = Array.isArray(json.tags) ? json.tags : [];
    return {
      title: clean(json.title, 120) || clean(fallbackTitle, 120) || 'Untitled snippet',
      summary: clean(json.summary, 600),
      tags: [...new Set(tags.map((t) => clean(t, 30).toLowerCase().replace(/^#/, '')).filter(Boolean))].slice(0, 4),
    };
  }

  Object.assign(SoroAgent, {
    PERSONA,
    DEFAULT_PROMPTS,
    renderTemplate: render,
    pageVars,
    buildMessages,
    parseJsonLoose,
    parseAiCheck,
    parseAiScores,
    verdictFor,
    parseSnippetMeta,
  });
})(globalThis);
